#!/usr/bin/env node
// node scripts/build-course-words.mjs [--check] — writes src/data/courseWords.js: every German word
// form the live courses show (Lektionen with their dialogues, word fields, notices and guided texts;
// both lesson pools; both checkpoint reading banks), folded the way the checker folds an answer
// (normalizeAnswer: lower case, ä → ae, ß → ss). The checker reads it to tell a slip from another
// word: „isst“ for „ist“ is a word the course teaches, so it is another answer, not a typo
// (src/lib/lesson/check.js, realWordSlip). --check exits 1 when the committed file is stale.
// Run after `node scripts/build-lesson-pool.mjs` whenever course text changes.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { CURRICULA } from '../src/data/curricula/index.js';
import { HOEREN_A11 } from '../src/data/curricula/a11.hoeren.js';
import { LESEN_A11 } from '../src/data/curricula/a11.lesen.js';
import { LESEN_A12 } from '../src/data/curricula/a12.lesen.js';
import { normalizeAnswer } from '../src/utils/answerMatch.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const OUT = `${root}src/data/courseWords.js`;
// English and Arabic twins, ids and technical fields are not German the learner reads, and the
// guided flow's meaning and reading questions are answered in English, so are practice options of
// meaning tasks. German explanations count: the wrong forms they quote („nicht arbeitst“) are the very
// mistakes a task is about, so typing one is that mistake, not a slip.
const SKIP = /(En|Ar|Id|Ids)$|^(en|ar|id|slug|ruleSlug|grammarSlugs|primarySlug|kind|type|src|alt|flow|audio|voice|sha1|level|code|testSlug|examName|handlungsfeld|examTeile|links|meaning|questions|practiceRule|options|slot|count|thingKind|meaningLines|more|optionsDe)$/;
// (`slot`, `count` and `thingKind` are the final check's gap kind, number and kind of thing, „color", „one", „drink": not German.)

function strings(value, key = '') {
  if (typeof value === 'string') return SKIP.test(key) ? [] : [value];
  if (Array.isArray(value)) return value.flatMap((v) => strings(v, key));
  if (value && typeof value === 'object') return Object.entries(value).flatMap(([k, v]) => (SKIP.test(k) ? [] : strings(v, k)));
  return [];
}

export function courseWords() {
  const texts = [
    ...Object.values(CURRICULA).flatMap((c) => c.lektionen.flatMap((l) => strings(l))),
    ...['a11', 'a12'].flatMap((lv) => JSON.parse(readFileSync(`${root}src/data/lessonPools/${lv}.json`, 'utf8')).items
      .flatMap((i) => [i.type === 'error_correction' ? null : i.questionDe, i.answer, ...(i.accepted || []), i.explanationDe])),
    ...[LESEN_A11, LESEN_A12].flatMap((bank) => Object.values(bank).flatMap((c) => c.papers.flat()).flatMap((u) => [u.text, u.statement, u.question])),
    ...Object.values(HOEREN_A11).flatMap((c) => c.papers).flatMap((p) => [...p.say, ...p.read].map((u) => u.de).concat(p.hear.flatMap((u) => [u.text, u.question]))),
  ].filter((t) => typeof t === 'string');
  const words = new Set();
  for (const t of texts) for (const w of normalizeAnswer(t).split(/[^\p{L}]+/u)) if (w.length >= 2) words.add(w);
  return [...words].sort();
}

export function render(words) {
  const lines = [];
  let line = '';
  for (const w of words) {
    if (line.length + w.length + 1 > 100) { lines.push(line); line = ''; }
    line = line ? `${line} ${w}` : w;
  }
  if (line) lines.push(line);
  return '// Generated by scripts/build-course-words.mjs: every German word form the live courses show, folded like an\n' +
    '// answer (normalizeAnswer). Do not edit by hand; run the script after course text changes.\n' +
    `export const COURSE_WORDS = new Set(\`\n${lines.join('\n')}\n\`.split(/\\s+/).filter(Boolean));\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const words = courseWords();
  const text = render(words);
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n');
    if (current !== text) { console.error('src/data/courseWords.js is stale: run node scripts/build-course-words.mjs'); process.exit(1); }
    console.log(`courseWords.js is current (${words.length} words)`);
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote src/data/courseWords.js: ${words.length} words, ${text.length} bytes`);
  }
}
