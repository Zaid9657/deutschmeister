#!/usr/bin/env node
// Arabic coverage report for A1.1 (docs/arabic/README.md §4).
//
//   node scripts/i18n-coverage.mjs            → writes docs/arabic/coverage-a11.{md,json}, prints a summary
//   node scripts/i18n-coverage.mjs --check    → exit 1 if the PILOT scope has a missing or stale entry
//   node scripts/i18n-coverage.mjs --accept <key> [<key> …]
//                                              → re-stamp `src` of those sidecar entries after an
//                                                editor has re-checked the Arabic against the changed
//                                                source; the status stays `draft`.
//
// "Reachable" comes from scripts/lib/i18n-sources.mjs, which runs the real
// lesson builders over the whole draw cycle. Three sections:
//   1. pilot — Lektionen in SUPPORT_SCOPE['ar:a1.1'] plus the course-home copy: the release gate;
//   2. checkpoint after the scope (Checkpoint 1) — reported, not gated;
//   3. the rest of A1.1 — reported as untranslated (falls back to English, labelled).
// Plus the interface tables: the lesson chrome (src/lib/lesson/strings.js vs
// src/locales/ar/lesson.js) and the i18next keys the translated screens use.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CURRICULUM_A11 } from '../src/data/curricula/a11.js';
import { SUPPORT_SCOPE } from '../src/lib/lesson/support.js';
import { checkpointSupport, hashSource, reachableSupport, statusOf } from './lib/i18n-sources.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SIDECAR = join(ROOT, 'src/data/curricula/a11.ar.js');
const OUT_MD = join(ROOT, 'docs/arabic/coverage-a11.md');
const OUT_JSON = join(ROOT, 'docs/arabic/coverage-a11.json');

const pool = JSON.parse(readFileSync(join(ROOT, 'src/data/lessonPools/a11.json'), 'utf8'));

export async function loadSidecar() {
  const mod = await import(`${pathToFileURL(SIDECAR).href}?t=${Date.now()}`);
  return (mod.default || mod).entries || {};
}

const count = (list) => list.reduce((acc, r) => ({ ...acc, [r.status]: (acc[r.status] || 0) + 1 }), {});

export async function coverage() {
  const entries = await loadSidecar();
  const scope = SUPPORT_SCOPE['ar:a1.1'];
  const rows = (map, section) => [...map.values()].map((e) => ({ ...e, section, status: statusOf(e, entries[e.key]) }));

  const pilot = rows(reachableSupport({ pool, lektionIds: scope }), 'pilot');
  const pilotKeys = new Set(pilot.map((r) => r.key));
  const cp = rows(checkpointSupport({ pool, checkpointNr: 1 }), 'checkpoint-1').filter((r) => !pilotKeys.has(r.key));
  const restIds = CURRICULUM_A11.lektionen.map((l) => l.id).filter((id) => !scope.includes(id));
  const rest = rows(reachableSupport({ pool, lektionIds: restIds, includeCourse: false }), 'later-lektionen').filter((r) => !pilotKeys.has(r.key));

  // Interface tables.
  const { STRINGS } = await import('../src/lib/lesson/strings.js');
  const { default: AR_LESSON } = await import('../src/locales/ar/lesson.js');
  const enKeys = Object.keys(STRINGS.en);
  const lessonMissing = enKeys.filter((k) => typeof AR_LESSON[k] !== 'string' || !AR_LESSON[k].trim());

  const reachableKeys = new Set([...pilot, ...cp, ...rest].map((r) => r.key));
  const orphans = Object.keys(entries).filter((k) => !reachableKeys.has(k));
  const reviewedWithoutSignoff = Object.entries(entries)
    .filter(([, e]) => e.status === 'reviewed' && !(e.reviewer && e.reviewedOn))
    .map(([k]) => k);

  return {
    generatedOn: new Date().toISOString().slice(0, 10),
    scope,
    pilot: { total: pilot.length, ...count(pilot) },
    checkpoint1: { total: cp.length, ...count(cp) },
    laterLektionen: { total: rest.length, ...count(rest) },
    interface: { lessonKeys: enKeys.length, lessonMissing },
    orphans,
    reviewedWithoutSignoff,
    rows: [...pilot, ...cp, ...rest].map(({ key, section, scope: s, kind, status }) => ({ key, section, scope: s, kind, status })),
    problems: pilot.filter((r) => r.status === 'missing' || r.status === 'stale').map((r) => `${r.status}: ${r.key}`),
  };
}

function markdown(c) {
  const line = (name, s) => `| ${name} | ${s.total} | ${s.reviewed || 0} | ${s.draft || 0} | ${s.stale || 0} | ${s.missing || 0} |`;
  const byKind = {};
  for (const r of c.rows.filter((x) => x.section === 'pilot')) byKind[r.kind] = (byKind[r.kind] || 0) + 1;
  return [
    '# Arabic coverage — A1.1',
    '',
    `Generated by \`node scripts/i18n-coverage.mjs\` on ${c.generatedOn}. Do not edit by hand.`,
    '',
    'Reachable = what the real builders can show (every attempt of the draw cycle, every requeue',
    'candidate a miss can bring back, derived items, review cards, intro and course-home copy).',
    'Statuses: **reviewed** (signed off by a named human), **draft** (machine-authored),',
    '**stale** (the German/English source changed after translation), **missing**.',
    '',
    '| Section | Reachable keys | Reviewed | Draft | Stale | Missing |',
    '|---|---|---|---|---|---|',
    line(`Pilot: ${c.scope.join(', ')} + course home`, c.pilot),
    line('Checkpoint 1 (after Lektion 3) — not gated', c.checkpoint1),
    line('Lektionen 4–12 — untranslated, English fallback labelled', c.laterLektionen),
    '',
    `Lesson interface table: ${c.interface.lessonKeys} keys, ${c.interface.lessonMissing.length} missing in Arabic.`,
    `Sidecar entries no longer reachable (orphans): ${c.orphans.length}.`,
    `Entries marked reviewed without a named reviewer and date: ${c.reviewedWithoutSignoff.length}.`,
    '',
    '## Pilot keys by kind',
    '',
    '| Kind | Keys |',
    '|---|---|',
    ...Object.entries(byKind).sort().map(([k, n]) => `| ${k} | ${n} |`),
    '',
    c.problems.length ? `## Problems in the pilot scope\n\n${c.problems.map((p) => `- ${p}`).join('\n')}\n` : '## Problems in the pilot scope\n\nNone.\n',
  ].join('\n');
}

function accept(keys) {
  const all = new Map([
    ...reachableSupport({ pool, lektionIds: CURRICULUM_A11.lektionen.map((l) => l.id) }),
    ...checkpointSupport({ pool, checkpointNr: 1 }),
  ]);
  let src = readFileSync(SIDECAR, 'utf8');
  for (const key of keys) {
    const e = all.get(key);
    if (!e) { console.error(`not reachable: ${key}`); process.exitCode = 1; continue; }
    const esc = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const re = new RegExp(`('${esc}': \\{[^\\n]*?src: ')h[0-9a-f]{8}(')`);
    if (!re.test(src)) { console.error(`no sidecar entry: ${key}`); process.exitCode = 1; continue; }
    src = src.replace(re, `$1${hashSource(e.source)}$2`);
    console.log(`re-stamped ${key} (status unchanged)`);
  }
  writeFileSync(SIDECAR, src);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const args = process.argv.slice(2);
  if (args[0] === '--accept') {
    accept(args.slice(1));
  } else {
    const c = await coverage();
    mkdirSync(dirname(OUT_MD), { recursive: true });
    if (!args.includes('--check')) {
      writeFileSync(OUT_MD, markdown(c));
      writeFileSync(OUT_JSON, `${JSON.stringify({ ...c, rows: undefined }, null, 2)}\n`);
    }
    console.log(`pilot ${JSON.stringify(c.pilot)} · checkpoint-1 ${JSON.stringify(c.checkpoint1)} · later ${JSON.stringify(c.laterLektionen)}`);
    console.log(`lesson interface: ${c.interface.lessonKeys} keys, ${c.interface.lessonMissing.length} missing · orphans ${c.orphans.length}`);
    if (c.problems.length) {
      console.error(c.problems.join('\n'));
      if (args.includes('--check')) process.exit(1);
    }
  }
}
