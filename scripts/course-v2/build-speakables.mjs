#!/usr/bin/env node
// Course v2 speakables — every German text a course-v2 speaker button can play, per level, keyed
// by the id the player sends (owner 2026-10-01: "the voices are not working" — the browser's own
// voice is silent on many phones and in in-app browsers, so the course plays server-rendered audio).
//
//   node scripts/course-v2/build-speakables.mjs           write netlify/functions/_shared/course-v2/<level>.speak.json
//                                                          for every level in COURSE_AUDIO_LEVELS (_shared/courseAudio.mjs)
//   node scripts/course-v2/build-speakables.mjs --check   write nothing; exit 1 when a file is out of date
//
// Sources (the compiled course, src/data/course-v2/<level>/), and the id each one is played under:
//   lines.json         dialogue, exam and announcement lines        → the line id (a1.1-u01-start-l01)
//   words.json         word cards and word lists: nounParts().say   → the word id (lx.hallo)
//                      the word's example sentence                  → `<word id>-ex`
//   units/*.json       Redemittel cards (`redemittel[]`)            → the phrase id (a1.1-u06-rm01)
// Only these texts can be rendered: netlify/functions/course-audio.mjs looks the id up here and
// never speaks text the client sends. tests/course-v2-audio-server.test.mjs fails when a file is
// stale, so re-run this after every compile.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { nounParts } from '../../src/components/course-v2/kapitel.js';
import { COURSE_AUDIO_LEVELS } from '../../netlify/functions/_shared/courseAudio.mjs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const GENERATED_MARK = 'generated by scripts/course-v2/build-speakables.mjs from src/data/course-v2 — do not edit';
export const DATA_DIR = path.join(REPO_ROOT, 'src/data/course-v2');
export const OUT_DIR = path.join(REPO_ROOT, 'netlify/functions/_shared/course-v2');

const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const clean = (s) => (typeof s === 'string' ? s.trim() : '');

/**
 * The levels the server renders (COURSE_AUDIO_LEVELS) that have a compiled lines.json, sorted.
 * The held drafts get no file: nothing would serve it, and their edits would only make it stale.
 */
export function speakableLevels(dataDir = DATA_DIR) {
  if (!fs.existsSync(dataDir)) return [];
  return fs.readdirSync(dataDir)
    .filter((d) => COURSE_AUDIO_LEVELS.includes(d) && fs.existsSync(path.join(dataDir, d, 'lines.json')))
    .sort();
}

/**
 * The speakables of one level → { entries: { id: { t, k, az?, s?, r? } }, collisions: [id] }.
 *   t  the text to speak          k  'line' | 'word' | 'example' | 'phrase'
 *   az the cast's Azure voice (lines; null for announcements)   s  the speaker   r  the rate
 * The first source to claim an id wins; a second claim with a different text is a collision.
 */
export function buildSpeakables(level, dataDir = DATA_DIR) {
  const dir = path.join(dataDir, level);
  const entries = {};
  const collisions = [];
  const put = (id, entry) => {
    if (!id || !entry.t) return;
    if (entries[id]) {
      if (entries[id].t !== entry.t) collisions.push(id);
      return;
    }
    entries[id] = entry;
  };

  for (const l of readJson(path.join(dir, 'lines.json'))) {
    put(l.id, { t: clean(l.text), k: 'line', az: l.voice || null, s: l.speaker || null, r: l.rate || null });
  }

  const wordsFile = path.join(dir, 'words.json');
  if (fs.existsSync(wordsFile)) {
    for (const w of readJson(wordsFile).words || []) {
      put(w.id, { t: clean(nounParts(w).say), k: 'word' });
      if (clean(w.example)) put(`${w.id}-ex`, { t: clean(w.example), k: 'example' });
    }
  }

  const unitsDir = path.join(dir, 'units');
  if (fs.existsSync(unitsDir)) {
    for (const f of fs.readdirSync(unitsDir).filter((x) => x.endsWith('.json')).sort()) {
      for (const r of readJson(path.join(unitsDir, f)).redemittel || []) put(r.id, { t: clean(r.de), k: 'phrase' });
    }
  }

  const sorted = {};
  for (const id of Object.keys(entries).sort()) sorted[id] = entries[id];
  return { entries: sorted, collisions };
}

export function speakablesText(level, dataDir = DATA_DIR) {
  const { entries } = buildSpeakables(level, dataDir);
  return `${JSON.stringify({ $generated: GENERATED_MARK, level, entries }, null, 0)}\n`;
}

export const outFile = (level, outDir = OUT_DIR) => path.join(outDir, `${level}.speak.json`);

function main(argv) {
  const check = argv.includes('--check');
  let stale = 0;
  for (const level of speakableLevels()) {
    const { entries, collisions } = buildSpeakables(level);
    if (collisions.length) {
      console.error(`${level}: ${collisions.length} id(s) claimed twice with different text: ${collisions.slice(0, 5).join(', ')}`);
      process.exitCode = 1;
      return;
    }
    const text = speakablesText(level);
    const file = outFile(level);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === text) continue;
    if (check) {
      console.error(`${path.relative(REPO_ROOT, file)} is out of date — run node scripts/course-v2/build-speakables.mjs`);
      stale += 1;
    } else {
      fs.writeFileSync(file, text);
      console.log(`${path.relative(REPO_ROOT, file)}: ${Object.keys(entries).length} speakables`);
    }
  }
  if (check && stale) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
