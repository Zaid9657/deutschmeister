// Course v2 compiler v0 — deterministic, idempotent (SCHEMA §13).
//
// For one level it reads content/course-v2/** (registries shared, the level's own files) and
// produces, after a clean SCH-01/REF-01/KEY-01 check:
//
//   <out>/<level>/units/uNN.json      the unit chunk the player lazy-loads (units at stage T only):
//                                     learner-invisible fields stripped, generated fields added
//                                     (poolItems in the live lessonPools shape, generated-item ids,
//                                     line seconds, minutesPlanned, reviewCards, contentHash)
//   <out>/<level>/reserve.json        the reserve index (SCHEMA §13): every Lernschritt's reserve items
//                                     in the pool shape, by unit, step, topic and error tag — read by
//                                     requeue, earlierDraw, Plateau review sets, Mehr üben, repair cards
//   <out>/<level>/plateaus/pN.json, closing/<id>.json   the same treatment for Plateau/closing files;
//                                     a Plateau's `review.items` is its review set, DRAWN here from the
//                                     unit reserves (banks: ['plateau'], seeded by the Plateau id:
//                                     currentShare from the units since the previous Plateau, the rest
//                                     from the earlier ones); a .1 Halbtest gets `comesNext` — the first
//                                     unit of the .2 level whose Prüfungsfokus names each Teil (the
//                                     Teil-Karte), from that level's unit files or specs.json
//   <out>/<level>/manifest.json       course manifest: units with titles, can-dos, grammar, Prüfungsfokus,
//                                     minutes and counts (syllabus rows), Etappen, completion, review,
//                                     pace, counts for copy, contentHash
//   <out>/<level>/ids.ledger.json     every live id of the level + tombstones of removed ids (ID-01)
//   <out>/<level>/rule-cards.json     the level's rule cards (when authored)
//   <out>/<level>/words.json          the level's word list for the Kapitel „Wortschatz" page (when a lexicon exists)
//   <out>/<level>/lines.json          every spoken line with its cast voice — the audio run's input
//   <banks>/<level>.banks.json        grader input only, every entry keyed by bankKey:
//                                       writing  = WritingTasks (Leitpunkt cues and `choose` included,
//                                                  SCHEMA §15.5) + written MicroOutputs
//                                       speaking = SpeakingTasks + spoken MicroOutputs
//                                       micro    = every MicroOutput, with its `mode` (the lookup
//                                                  table of _shared/rubrics/data.mjs bankEntry(…, 'micro', key))
//
// PARTIAL LEVELS (compile mode). A level compiles from the units that exist: a unit course.json lists
// but no file holds yet is a manifest row with status 'coming' (title, can-dos, Prüfungsfokus and
// planned minutes from the level's specs.json bundle when it has one) and no chunk; a unit whose own
// check fails (SCH-01, REF-01, KEY-01 — its lane packs included) is SKIPPED with its errors returned,
// never half-written, and is listed as 'coming' too. References to a planned-but-missing unit (and to
// ids under it) resolve in compile mode only; the checker and the validator keep REF-01 as it is.
// Ids of a unit that is not compiled in a run stay live in the ledger — only a unit that compiles can
// tombstone its removed ids. Errors in any other file of the level or in a shared registry, and the
// compile-stage integrity errors (ID-01 duplicates and tombstones, KEY-01 prefix/duplicates) still
// refuse the whole level.
//
// Nothing here reads a clock, the environment or the network: the same content gives the same bytes.
