const UNIT_OF_ID = /^((?:a1|a2|b1|b2)\.[12]-u(?:0[1-9]|1[0-2]))(?:-|$)/;
/** The unit an id lives under ('a1.1-u04-ls1-p03' → 'a1.1-u04'; bank key 'a11-u04-w' → 'a1.1-u04'), or null. */
export function unitOfId(id) {
  if (typeof id !== 'string') return null;
  const m = id.match(UNIT_OF_ID);
  if (m) return m[1];
  const b = parseBankKey(id);
  return b && /^u\d{2}$/.test(b.slot) ? `${levelOfPrefix(b.prefix)}-${b.slot}` : null;
}

/** The level directory a file sits in (`<root>/<level>/…`), or null. */
function levelOfFile(file, contentRoot) {
  const first = path.relative(contentRoot, file).split(path.sep)[0];
  return PATTERNS.LEVEL.test(first) ? first : null;
}

/**
 * The unit a file belongs to: a unit file or one of its lane packs, by the document's own id or
 * — when it cannot be parsed or has no valid id — by its path `<level>/units/uNN[.lane-x].json`.
 */
function unitOfFile(t, contentRoot) {
  if (!t.error && t.kind === 'unit' && typeof t.doc.id === 'string' && PATTERNS.UNIT.test(t.doc.id)) return t.doc.id;
  if (!t.error && t.kind === 'lanepack' && typeof t.doc.unit === 'string' && PATTERNS.UNIT.test(t.doc.unit)) return t.doc.unit;
  const m = path.relative(contentRoot, t.file).split(path.sep).join('/').match(/^((?:a1|a2|b1|b2)\.[12])\/units\/u(0[1-9]|1[0-2])(?:\.lane-[a-z0-9]+)?\.json$/);
  return m && (t.error || t.kind === 'unit' || t.kind === 'lanepack') ? `${m[1]}-u${m[2]}` : null;
}

/**
 * `<level>/specs.json` — the curriculum agents' spec bundle (an array of spec units, not a SCHEMA
 * file; RAILS §8). The checker reports it; the compiler reads it only as syllabus input for units
 * that have no file of their own yet.
 */
function isSpecBundle(t, contentRoot) {
  const r = path.relative(contentRoot, t.file).split(path.sep);
  return r.length === 2 && r[1] === 'specs.json' && PATTERNS.LEVEL.test(r[0]) && Array.isArray(t.doc);
}

/** The index a compile run checks against: references to planned-but-missing units resolve. */
function withPlannedUnits(index, missing) {
  if (!index || missing.size === 0) return index;
  return {
    ...index,
    has(kind, id) {
      const found = index.has(kind, id);
      if (found !== false) return found;
      const owner = kind === 'unit' ? id : ['step', 'item', 'line', 'text', 'asset', 'fact', 'fokus', 'bank'].includes(kind) ? unitOfId(id) : null;
      return owner && missing.has(owner) ? true : found;
    },
  };
}

const strs = (x) => (Array.isArray(x) ? x.filter((v) => typeof v === 'string') : []);
const str = (x) => (typeof x === 'string' && x ? x : null);

/** Visit every object/array in document order. */
function eachNode(root, fn) {
  const visit = (x, parent) => {
    if (Array.isArray(x)) {
      x.forEach((y) => visit(y, x));
      return;
    }
    if (!isObj(x)) return;
    fn(x, parent);
    for (const v of Object.values(x)) visit(v, x);
  };
  visit(root, null);
}

