// The database half of src/data/lessonPools/<level>.corrections.json: one UPDATE per
// grammar_exercises row whose shipped pool text differs from the cache (the reviewed sidecar
// English the pool build now prefers, and the field-level corrections). Prints SQL; nothing is
// applied — migrations are hand-applied (migrations/README.md).
//
//   node scripts/pool-corrections-sql.mjs a1.1 > migrations/<date>-a11-exercise-text-fixes.sql
import { readFileSync } from 'node:fs';

const level = (process.argv[2] || 'a1.1').toLowerCase();
const key = level.replace('.', '');
const read = (p) => JSON.parse(readFileSync(new URL(`../${p}`, import.meta.url), 'utf8'));
const cache = read('grammar-content-cache.json');
const pool = read(`src/data/lessonPools/${key}.json`).items;
const fixes = read(`src/data/lessonPools/${key}.corrections.json`).items || {};

const rows = new Map(cache.exercises.map((e) => [e.id, e]));
const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `${q(JSON.stringify(v))}::jsonb`;

const updates = [];
for (const it of pool) {
  const row = rows.get(it.id);
  if (!row) continue; // generated or hand-written: not a database row
  const fix = fixes[it.id] || {};
  const set = [];
  if ((row.explanation_en || row.why_correct_en || '') !== it.explanationEn) set.push(`explanation_en = ${q(it.explanationEn)}`);
  if ('explanationDe' in fix && (row.explanation_de || row.why_correct_de || '') !== it.explanationDe) set.push(`explanation_de = ${q(it.explanationDe)}`);
  if ('questionEn' in fix && row.question_en !== it.questionEn) set.push(`question_en = ${q(it.questionEn)}`);
  if ('questionDe' in fix && row.question_de !== it.questionDe) set.push(`question_de = ${q(it.questionDe)}`);
  if ('hint' in fix && row.hint !== it.hint) set.push(`hint = ${q(it.hint)}`);
  if ('accepted' in fix) set.push(`acceptable_answers = ${json(it.accepted)}`);
  if ('options' in fix) set.push(`options = ${json(it.options)}`);
  if (set.length) updates.push(`UPDATE public.grammar_exercises SET ${set.join(', ')} WHERE id = ${q(it.id)};`);
}

console.log([
  `-- ${level.toUpperCase()} exercise text fixes — the database half of src/data/lessonPools/${key}.corrections.json.`,
  '--',
  '-- NOT APPLIED. Apply by hand in the Supabase SQL editor (migrations/README.md). Data only, no schema.',
  `-- What it does: brings ${updates.length} grammar_exercises rows in line with what the course pool ships —`,
  '-- the reviewed sidecar English the pool build used to ignore for bank rows (the L8 „hour + Uhr +',
  '-- minutes“ explanation among them) and the field-level corrections (explanations, accepted answers,',
  '-- an option set, prompts).',
  '-- Why: the Astro grammar pages and the next grammar-content-cache.json dump read these rows. After',
  '-- applying: node scripts/dump-grammar-cache.mjs, rebuild the pool, and remove every correction the',
  '-- build then reports as STALE.',
  `-- Generated by scripts/pool-corrections-sql.mjs ${level}.`,
  '',
  'BEGIN;',
  ...updates,
  'COMMIT;',
].join('\n'));
