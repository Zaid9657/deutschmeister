/** Optional Arabic help keyed by the complete English task, not a third interface language. */
export function taskArabic(taskEn = '') {
  if (TASKS_AR[taskEn]) return TASKS_AR[taskEn];
  let m = taskEn.match(/^Fill the gap with the right form of “(.+)”\.$/u);
  if (m) return `أكمل الفراغ بالصيغة المناسبة للفعل ${m[1]}.`;
  m = taskEn.match(/^Fill the gap with the word that goes with “(.+)”\.$/u);
  if (m) return `أكمل الفراغ بالكلمة التي تناسب ${m[1]}.`;
  m = taskEn.match(/^Build the (sentence|question)\. Begin with “(.+)”\.$/u);
  if (m) return `رتّب الكلمات لتكوين ${m[1] === 'question' ? 'سؤال' : 'جملة'}. ابدأ بـ ${m[2]}.`;
  return null;
}
export function feedbackArabic(key, values = {}) {
  return (FEEDBACK_AR[key] || '').replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}
