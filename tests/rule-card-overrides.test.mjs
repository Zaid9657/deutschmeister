// (c) ── du-register.
//
// The banned forms are the ones review #4 quoted plus the du-imperatives the
// pool normaliser already removes. ONE exemption, deliberately narrow and
// mechanical: a PARADIGM LINE — a line that names the persons, i.e. one
// carrying both `ich` and `du` as standalone words ("ich bin, du bist, er ist",
// "ich komme, du kommst → Komm!"). There `du` and `dein` are the grammar being
// taught, not an address to the reader; anywhere else they are the register bug.
// Nothing weaker is allowed: a bare "Du bist müde." or "Antworte mit einem Satz"
// carries no `ich` and therefore fails.
const DU_REGISTER_RE = /\b(du|dir|dich|dein\w*|sagst|lerne|antworte|tippe|kannst)\b/i;
// A PERSONAL paradigm names the persons (`ich … du …`); a POSSESSIVE paradigm
// names the possessive articles (`mein … dein …`) and is the same thing one word
// class over — it is what A1.1 Lektion 12 and its notice TITLE are made of
// ("mein, dein, sein, ihr – Possessivartikel"), and a card whose title must equal
// its notice title cannot drop the `dein` out of that listing. Both forms are
// closed: two named forms on one line, never a bare `du`/`dein` addressed at the
// reader.
const isParadigmLine = (text) =>
  (/\bich\b/i.test(text) && /\bdu\b/i.test(text)) || (/\bmein\b/i.test(text) && /\bdein\b/i.test(text));

test('no card duzt outside a paradigm listing', () => {
  for (const primary of PRIMARIES) {
    const card = cardOf(primary.slug);
    const checked = [
      ['titleDe', card.titleDe],
      ...germanLines(card).map((line, i) => [`content line ${i + 1}`, line]),
      ...mistakeFields(card).map((field, i) => [`commonMistakes field ${i}`, field]),
    ];
    for (const [at, text] of checked) {
      if (isParadigmLine(text)) continue;
      const hit = DU_REGISTER_RE.exec(text);
      assert.equal(
        hit,
        null,
        `${where(primary)} ${at}: du-register "${hit && hit[0]}" outside a paradigm line — "${text}"`,
      );
    }
  }
});

