//
// HOW A NOUN IS FOUND. German capitalises nouns, so a capitalised token that is
// NOT at the start of a sentence is a noun. "Start of a sentence" resets at the
// beginning of a line and after `.`, `?`, `!`, `:`, `—` or `→` — the colon
// matters because these cards are written as "Frage: Wie schreibt man das?", and
// the arrow because what follows one is a quoted FORM that starts its own
// sentence ("ich komme, du kommst → Komm!"). The arrow costs a little coverage —
// the one token after it is not checked against the Wortfeld — and the
// alternative was an open-ended allow-list of capitalised imperatives, which is
// the kind of list that quietly grows until it covers everything.
//
// HOW IT IS MATCHED. Against the `word` values of every Wortfeld entry the course
// has taught BY that Lektion — for a level after the first that means the WHOLE
// Wortfeld of every earlier level plus its own Lektion 1 … N — split into single
// words (so "Guten Tag" yields Tag and "Gäste einladen" yields Gäste). A token
// counts as covered when a Wortfeld form is a PREFIX of it (Buchstabe →
// Buchstaben, Heft → Hefte) or a SUFFIX of it (German compounds are head-final:
// Artikel → Possessivartikel). Umlaut plurals are deliberately NOT resolved —
// write "die Hefte", not "die Bücher", and the card stays inside the lexis it can
// point at.
//
// Everything a card may legitimately name beyond that lexis is listed below, by
// kind, and every list is closed.
// META_NOUNS, CONSTRUCTION_PATTERNS and isMetaNoun now live in
// `src/data/curricula/constructions.js` so that this guard and RULE 15b in
// `scripts/validate-curriculum.mjs` read ONE definition (DaF review #11, MAJOR 3).
// The list itself is unchanged; see that module for its per-entry history.

/** Letter NAMES, which the A1.1 L1 card must spell out — they are names, not lexis. */
const LETTER_NAMES = ['Jot', 'Vau', 'We', 'Ypsilon', 'Zett', 'Eszett', 'Umlaut', 'Zed'];

/** The polite Sie/Ihr paradigm, capitalised by rule rather than by word class. */
const POLITE_FORMS = ['Sie', 'Ihr', 'Ihre', 'Ihren', 'Ihrem', 'Ihnen'];

/** Proper nouns: people and places. Reuses the curricula's own lists. */
const PROPER_NAMES = [...DIALOG_NAMES_A11, ...DIALOG_NAMES_A12, 'Marokko', 'Schweiz', 'Meier'];

/**
 * The nouns-gender card demonstrates gender-PREDICTING ENDINGS. An ending is
 * shown on words that carry it, and A1.1's Wortfeld happens to contain exactly
 * one (-ung: die Entschuldigung). These five are the -heit/-keit/-schaft/-chen/
 * -lein demonstrations; they are the card's subject matter, not its situation.
 */
const GENDER_ENDING_EXAMPLES = ['Freiheit', 'Möglichkeit', 'Freundschaft', 'Mädchen', 'Brötchen'];

/**
 * Wortfeld words a card needs BEFORE the Lektion that teaches them. Kept to the
 * cases that exist: `im` governs month names, so the A1.1 L8 clock card cannot
 * state its own rule without naming a month, and A1.1 teaches Monat and Mai in
 * L12 — the A1.2 number card inherits the same pair for "der zwanzigste Mai".
 * Anything added here is a card reaching outside its own course-so-far and must
 * be argued, not assumed.
 */
const EARLY_USE = { 'time-and-dates': ['Monat', 'Mai', 'Datum'], 'numbers-counting': ['Mai'] };

const ALWAYS_ALLOWED = [...META_NOUNS, ...LETTER_NAMES, ...POLITE_FORMS, ...PROPER_NAMES, ...GENDER_ENDING_EXAMPLES];

const splitWords = (text) => String(text).split(/[^A-Za-zÄÖÜäöüß]+/).filter(Boolean);

/**
 * Every Wortfeld word the course has taught by Lektion `nr` of `level`: the full
 * Wortfeld of every earlier level, plus this level's Lektion 1 … nr. Lowercased
 * and split into single words.
 */
const cumulativeWortfeld = (level, nr) => {
  const forms = new Set();
  for (const lvl of LEVELS) {
    if (lvl > level) continue;
    for (const lektion of ALL_CURRICULA[lvl].lektionen) {
      if (lvl === level && lektion.nr > nr) continue;
      for (const entry of lektion.wortfeld) {
        for (const word of splitWords(entry.word)) forms.add(word.toLowerCase());
        // ROUND 18 (DaF review #17, MAJOR 2): a paired person noun whose Lektion is at its 25-slot
        // ceiling carries the masculine in its gloss — `die Marokkanerin` … `(m: der Marokkaner,
        // Pl. die Marokkaner)`. That form is taught on the Lektion's notice (tests/curricula.test.mjs
        // pins that every `(m: …)` gloss reaches an input surface), so a card may say it. Read
        // from the gloss, never typed: the licence ends where the gloss does.
        for (const m of String(entry.en || '').matchAll(/\(m:\s*(?:der|die|das)?\s*([A-Za-zÄÖÜäöüß]+)/g)) forms.add(m[1].toLowerCase());
      }
    }
  }
  return [...forms].filter((w) => w.length >= 3);
};

/** Capitalised tokens that are not sentence-initial — i.e. the nouns of the text. */
const nounTokens = (text) => {
  const found = [];
  let atSentenceStart = true;
  for (const token of String(text).split(/\s+/)) {
    const bare = token.replace(/^[^A-Za-zÄÖÜäöüß]+/, '').replace(/[^A-Za-zÄÖÜäöüß]+$/, '');
    if (bare && !atSentenceStart && /^[A-ZÄÖÜ][a-zäöüß]+$/.test(bare)) found.push(bare);
    if (bare) atSentenceStart = false;
    if (/[.?!:—→]$/.test(token)) atSentenceStart = true;
  }
  return found;
};

test('every example noun stands in the Wortfeld the course has taught by that Lektion', () => {
  for (const primary of PRIMARIES) {
    const forms = cumulativeWortfeld(primary.level, primary.nr);
    const allowed = new Set([...ALWAYS_ALLOWED, ...(EARLY_USE[primary.slug] || [])].map((w) => w.toLowerCase()));
    // Prefix/suffix matching applies to the allow-lists too: "Name" covers
    // "Namen", "Artikel" covers "Possessivartikel".
    const covered = (token) => {
      const low = token.toLowerCase();
      return [...allowed, ...forms].some((form) => low === form || low.startsWith(form) || low.endsWith(form));
    };

    const card = cardOf(primary.slug);
    const offenders = [...new Set(
      [...germanLines(card), ...mistakeFields(card)].flatMap(nounTokens).filter((t) => !covered(t)),
    )];
    assert.deepEqual(
      offenders,
      [],
      `${where(primary)}: nouns outside the Wortfeld taught by Lektion ${primary.nr}: ${offenders.join(', ')}`,
    );
  }
});

